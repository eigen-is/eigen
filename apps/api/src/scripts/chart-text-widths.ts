// Writes the advance-width table measureLabel sums for every bundled font, from the static TTFs a docx embeds. Their
// Bold slots are the weight the editor draws bold in. Run it by hand after a font changes, and commit its output.
//
// Usage: bun apps/api/src/scripts/chart-text-widths.ts

import * as fs from 'node:fs';
import path from 'node:path';
import { EIGEN_FONTS } from '@workspace/lib/constants/fonts';
import type { FaceWidths } from '@workspace/lib/vector';
import { TEXT_WIDTH_RANGES } from '@workspace/lib/vector';
import { DOCX_FONT_FILES, sfntTables } from '../lib/export/doc/docx/fonts';

const OUT = path.join(import.meta.dir, '../../../../packages/lib/src/vector/text-width-data.ts');

const CODE_POINTS = TEXT_WIDTH_RANGES.flatMap(([first, last]) =>
    Array.from({ length: last - first + 1 }, (_, i) => first + i),
);

function faceWidths(file: string): FaceWidths {
    const tables = sfntTables(fs.readFileSync(file));
    const table = (tag: string): Buffer => {
        const found = tables.get(tag);
        if (!found) throw new Error(`${file} has no ${tag} table`);
        return found;
    };
    const unitsPerEm = table('head').readUInt16BE(18);
    const metricCount = table('hhea').readUInt16BE(34);
    const hmtx = table('hmtx');
    const glyphOf = cmapFormat4(table('cmap'));
    const advanceOf = (glyph: number): number =>
        Math.round((hmtx.readUInt16BE(4 * Math.min(glyph, metricCount - 1)) * 1000) / unitsPerEm);

    const mapped = CODE_POINTS.map((code) => {
        const glyph = glyphOf(code);
        return glyph === 0 ? null : advanceOf(glyph);
    });
    // Code points past the table, CJK and emoji included, reserve the face's widest Latin advance, about an em.
    const fallback = Math.max(...mapped.map((advance) => advance ?? 0));
    return { advances: mapped.map((advance) => advance ?? fallback), fallback };
}

// The Unicode BMP subtable (platform 3 encoding 1, or platform 0), format 4: segments of code points mapped by a delta
// or through the glyph id array.
function cmapFormat4(cmap: Buffer): (code: number) => number {
    let offset = -1;
    for (let i = 0; i < cmap.readUInt16BE(2); i++) {
        const record = 4 + i * 8;
        const platform = cmap.readUInt16BE(record);
        const encoding = cmap.readUInt16BE(record + 2);
        const subtable = cmap.readUInt32BE(record + 4);
        if ((platform === 3 && encoding === 1) || platform === 0) {
            if (cmap.readUInt16BE(subtable) === 4) offset = subtable;
        }
    }
    if (offset < 0) throw new Error('no format 4 cmap subtable');
    const segCountX2 = cmap.readUInt16BE(offset + 6);
    const ends = offset + 14;
    const starts = ends + segCountX2 + 2;
    const deltas = starts + segCountX2;
    const rangeOffsets = deltas + segCountX2;
    return (code) => {
        for (let seg = 0; seg < segCountX2; seg += 2) {
            if (cmap.readUInt16BE(ends + seg) < code) continue;
            const start = cmap.readUInt16BE(starts + seg);
            if (start > code) return 0;
            const delta = cmap.readUInt16BE(deltas + seg);
            const rangeOffset = cmap.readUInt16BE(rangeOffsets + seg);
            if (rangeOffset === 0) return (code + delta) & 0xffff;
            const glyph = cmap.readUInt16BE(rangeOffsets + seg + rangeOffset + 2 * (code - start));
            return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
        }
        return 0;
    };
}

const faces = Object.fromEntries(
    EIGEN_FONTS.map(({ name }) => {
        const files = DOCX_FONT_FILES.get(name);
        if (!files) throw new Error(`no font files for ${name}`);
        return [name, { regular: faceWidths(files.Regular), bold: files.Bold && faceWidths(files.Bold) }];
    }),
);

fs.writeFileSync(
    OUT,
    `// Generated by apps/api/src/scripts/chart-text-widths.ts from the bundled TTFs; rerun it after a face changes.

import type { FaceWidths } from './text-width';

export const TEXT_WIDTHS: Record<string, { regular: FaceWidths; bold?: FaceWidths }> = ${JSON.stringify(faces)};
`,
);
Bun.spawnSync(['bunx', 'biome', 'format', '--write', OUT]);
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
