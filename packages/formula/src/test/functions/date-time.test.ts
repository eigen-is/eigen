// The fixture of Excel batch 8 (family-date.md). 45000 is Wednesday 15 March 2023, D1 is 29 February 2024. From
// serial 61 on the rows are Excel's; below it the day line is Google's (google-dates.md), one real calendar.
const SHEET: Cells = {
    ...{ A1: 1.5, A2: -2.5, A3: 0, A4: 10, A5: 1e300 },
    ...{ B2: '3', B3: true, B4: '=1/0', B5: 'abc', B6: '=""' },
    ...{ C1: 2, C2: 4, C3: 6 },
    ...{ D1: 45351, D2: 45000.75, D3: 0, D4: 60, D5: 61, D6: -1, D7: 2958465, D8: 2958466 },
    ...{ D9: '2024-03-15', D10: '15 March 2024', D12: '12:30 PM', D13: 0.999999999, D14: 1.5 },
    ...{ F1: 45002, F2: 'x', F4: '=1/0', F5: 45002, F6: 45003 },
    ...{ G1: 45002, G2: 45003, G3: 45003 },
};

type Row = readonly [formula: string, expected: number | FormulaError];

// Excel's answers are recorded to 15 digits, so a number agrees when its first 12 do.
function rows(table: readonly Row[]) {
    test.each(table)('%s is %p', (formula, expected) => {
        const value = evaluate(formula, SHEET);
        if (typeof expected === 'number' && typeof value === 'number' && !Number.isInteger(expected)) {
            expect(Math.abs(value - expected)).toBeLessThanOrEqual(Math.abs(expected) * 5e-12);
        } else expect(value).toBe(expected);
    });
}

