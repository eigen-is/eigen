import { describe, expect, test } from 'bun:test';
import { DIV0, NA, NUM, VALUE } from '../../index';
import type { Cells } from '../recalc/support';
import { evaluate } from '../recalc/support';

// The sheet Excel's answers were recorded on. B1 is blank.
const SHEET: Cells = {
    A1: 1.5,
    A2: -2.5,
    A3: 0,
    A4: 10,
    A5: 1e300,
    B2: '3',
    B3: true,
    B4: '=1/0',
    B5: 'abc',
    B6: '=""',
    C1: 2,
    C2: 4,
    C3: 6,
};

type Row = readonly [formula: string, expected: number | boolean | typeof NUM];

// Excel's answer itself.
function exact(rows: readonly Row[]): void {
    test.each(rows)('%s is %p', (formula, expected) => {
        expect(evaluate(formula, SHEET)).toBe(expected);
    });
}

// Excel's answer in the 15 digits it shows.
function close(rows: readonly Row[]): void {
    test.each(rows)('%s is %p', (formula, expected) => {
        const value = evaluate(formula, SHEET);
        const shown = typeof value === 'number' ? Number(value.toPrecision(15)) : value;
        expect(shown).toBe(typeof expected === 'number' ? Number(expected.toPrecision(15)) : expected);
    });
}

