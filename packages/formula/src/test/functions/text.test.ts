import type { Cells } from '../recalc/support';
import { evaluate } from '../recalc/support';

const EMOJI = String.fromCodePoint(128512);
const NBSP = String.fromCharCode(160);

// The fixture of the text sheets of Excel batch 8. B1 is blank, D6 is 300 times x, D10 an emoji and an a.
const SHEET: Cells = {
    A1: 1.5,
    A2: -2.5,
    A3: 0,
    A4: 10,
    A5: 1e300,
    B2: '3',
    B3: true,
    B4: DIV0,
    B5: 'abc',
    B6: '=""',
    D1: 'Hello World',
    D2: '  two  spaces  ',
    D3: 'straße',
    D4: 'ÀÉÎõü',
    D5: 'a~*?b',
    D6: 'x'.repeat(300),
    D7: '1,234.50',
    D10: `${EMOJI}a`,
};

type Row = readonly [formula: string, expected: ReturnType<typeof evaluate>];

function rows(name: string, table: readonly Row[]) {
    test.each(table)(`${name}: %s is %p`, (formula, expected) => {
        expect(evaluate(formula, SHEET)).toBe(expected);
    });
}

