export type Step =
    | { kind: 'lines'; insert: boolean; rows: boolean; sheet: string; index: number; count: number }
    | { kind: 'move' | 'copy'; from: string; to: string }
    | { kind: 'fill' | 'sort'; sheet: string; range: string }
    | { kind: 'renameSheet'; from: string; to: string }
    | { kind: 'deleteSheet' | 'addSheet'; name: string }
    | { kind: 'copySheet'; name: string; newName: string }
    | { kind: 'nothing' | 'undo' | 'redo' | 'cellShift' | 'lineMove' };

