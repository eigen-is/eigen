import { describe, expect, test } from 'bun:test';
import { parseNumber } from '../../values/parse-number';

const taken = (cases: [string, number][]) => {
    for (const [text, value] of cases) expect([text, parseNumber(text)]).toEqual([text, value]);
};
const refused = (texts: string[]) => {
    for (const text of texts) expect([text, parseNumber(text)]).toEqual([text, undefined]);
};

describe('plain numbers', () => {
    test("the oracle's forms", () => {
        taken([
            ['1', 1],
            ['7', 7],
            ['1e3', 1000],
            [' 1 ', 1],
            ['.5', 0.5],
            ['5.', 5],
            ['1e-5', 0.00001],
            ['1E+3', 1000],
            ['10E3', 10000],
            ['0', 0],
            ['007', 7],
            ['1.5', 1.5],
            ['123456789012', 123456789012],
            ['0.1', 0.1],
            ['2.675', 2.675],
            ['1.7976931348623157e308', 1.79769313486231e308],
            ['1e-320', 1e-320],
            ['1.5e-30', 1.5e-30],
            ['1e25', 1e25],
        ]);
    });

    test('Excel batch 3: text handed to a function as a number', () => {
        taken([
            ['1', 1],
            ['2', 2],
            ['5', 5],
            ['1e-14', 1e-14],
            ['1E-014', 1e-14],
            ['1E14', 1e14],
            ['100000000000000000000', 1e20],
            ['123456789012345678', 123456789012345000],
            ['0.000000000000123456', 1.23456e-13],
            ['-0.00000000000001', -1e-14],
            ['1E-19', 1e-19],
            ['1E+20', 1e20],
            ['1.5E+25', 1.5e25],
            ['10000000000000000000', 1e19],
            ['0.000000000000000001', 1e-18],
        ]);
        refused(['TRUE', 'true', 'x', '']);
    });

    test('a sign in front, never negative zero', () => {
        refused(['5-', '$5-', '5%-']);
        taken([
            ['-5', -5],
            ['+5', 5],
            ['-1.5e3', -1500],
            ['  -5  ', -5],
        ]);
        expect(Object.is(parseNumber('-0'), 0)).toBe(true);
        expect(Object.is(parseNumber('(0)'), 0)).toBe(true);
    });

    test('digits past the 15th become zeros, as a typed number keeps them', () => {
        taken([
            ['123456789012345678', 123456789012345000],
            ['1234567890123456', 1234567890123450],
            ['1234567890123459', 1234567890123450],
            ['0.1234567890123456789', 0.123456789012345],
            ['0.000123456789012345678', 0.000123456789012345],
            ['1.99999999999999999', 1.99999999999999],
        ]);
    });

    test('what is no number', () => {
        refused([
            '',
            ' ',
            '   ',
            'abc',
            'TRUE',
            'true',
            '1.000,5',
            '0x1A',
            '1e',
            '1e+',
            'Infinity',
            '-Infinity',
            'NaN',
        ]);
        refused(['1 2', '.', '-', '+', '--5', '+-5', '5--', '-5-', '1.5.5', '1_000', '1e3.5', '1e1e1', 'e3', '1 e3']);
        refused(['- 23', '2 3', '5 -', '3 000', ' 5', '5\t', '１２', '1e999', '#N/A', '="1"', "'5"]);
    });
});

describe('thousands separators', () => {
    test('between groups of three', () => {
        taken([
            ['1,000', 1000],
            [' 1,000 ', 1000],
            ['-1,000.5', -1000.5],
            ['123,456.67', 123456.67],
            ['1,234,567', 1234567],
            ['12,345', 12345],
            ['1,000e3', 1000000],
        ]);
    });

    test('anywhere else the text is no number', () => {
        refused(['12,34', '1,00', '1,0000', '1,000,00', ',5', ',500', '1,,000', '1.5,000', '1234,567', '1,000,', '1,']);
    });
});

describe('percent, currency and brackets', () => {
    test('percent', () => {
        taken([
            ['10%', 0.1],
            ['50%', 0.5],
            ['40%', 0.4],
            ['23.123%', 0.23123],
            ['9 %', 0.09],
            ['-5%', -0.05],
            ['1e3%', 10],
        ]);
        refused(['%', '%10', '9%%', '3%22', '10% %']);
    });

    test('a dollar or euro sign in front or behind', () => {
        taken([
            ['$5', 5],
            ['$1,000', 1000],
            ['$ 5', 5],
            ['-$5', -5],
            ['$-5', -5],
            ['5$', 5],
            ['23€', 23],
            ['€12', 12],
            ['$5%', 0.05],
        ]);
        refused(['$', '$$5', '$5$', '£5', '¥5', '5 $', '-$-5', 'USD 5', '$ ']);
    });

    test('brackets make a number negative', () => {
        taken([
            ['(5)', -5],
            ['($5)', -5],
            ['(5%)', -0.05],
            ['(1,000.5)', -1000.5],
            [' (5) ', -5],
        ]);
        refused(['(5', '5)', '-(5)', '(-5)', '(5)-', '()', '((5))', '( 5 )']);
    });
});

describe('fractions', () => {
    test('a whole number, a space and a fraction', () => {
        taken([
            ['1 1/2', 1.5],
            ['0 1/2', 0.5],
            ['-1 1/2', -1.5],
            ['2 3/4', 2.75],
            ['1  1/2', 1.5],
            ['0 1/3', 1 / 3],
        ]);
    });

    test('a fraction alone is a date that needs the year, and no number here', () => {
        refused(['1/2', '1 2', '1 1/0', '1 1/', '1 /2', '1 1/2/3', '1.5 1/2', '1 1/2%', '1 1 /2']);
    });
});

