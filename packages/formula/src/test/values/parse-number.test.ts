describe('times', () => {
    test('hours and minutes, seconds and parts of a second', () => {
        taken([
            ['12:00', 0.5],
            ['13:30', 0.5625],
            ['4:35', 275 / 1440],
            ['04:35', 275 / 1440],
            ['16:35', 995 / 1440],
            ['0:00', 0],
            ['13:30:15', 48615 / 86400],
            ['4:35:00.5', 0.19097800925925926],
            ['4:35:00.999', 0.19098378472222222],
            ['4:5', 245 / 1440],
            ['4 : 35', 275 / 1440],
            ['4 :35', 275 / 1440],
            ['4: 35 PM', 995 / 1440],
            ['1/5/2026 4 : 35', 46027 + 275 / 1440],
        ]);
    });

    test('hours past a day count on', () => {
        taken([
            ['25:30', 1.0625],
            ['24:00', 1],
            ['48:00:00', 2],
        ]);
    });

    test('AM and PM', () => {
        taken([
            ['1:30 PM', 0.5625],
            ['4:35 AM', 275 / 1440],
            ['4:35 Am', 275 / 1440],
            [' 4:35 PM ', 995 / 1440],
            ['4 pm', 16 / 24],
            ['4:5 pm', 965 / 1440],
            ['4:05:20 pm', 57920 / 86400],
            ['12:00 AM', 0],
            ['12:00 PM', 0.5],
            ['12:30 AM', 30 / 1440],
            ['1:30 p', 0.5625],
            ['1:30 a', 90 / 1440],
        ]);
    });

    test('what is no time', () => {
        refused([
            '4:35pm',
            '13:00 PM',
            '4:35 A.M.',
            '0:0:86400',
            ':35',
            '4::35',
            '4:35 PMx',
            '-4:35 AM',
            '4:',
            '4:35:',
        ]);
        refused(['0:75', '23:59:60', '1:30PM', 'PM', ' pm', '4:35:00.', '4:35.5', '12345:00', '4 xm', '4:35 M']);
    });

    test('a date and a time', () => {
        taken([
            ['1/31/2020 6:00', 43861.25],
            ['2026-01-05 13:30', 46027.5625],
            ['2026-07-16 4:35 PM', 46219 + 995 / 1440],
            ['Jan 5, 2026 1:30 PM', 46027.5625],
            ['5-Jan-2026  13:30:00', 46027.5625],
            ['2026-01-01 24:00:00', 46024],
            ['1/5/2026 4 pm', 46027 + 16 / 24],
        ]);
        refused([
            '1/31/2020 6',
            '6:00 1/31/2020',
            '1/31/20206:00',
            '2026-01-05 13:30 x',
            '2/30/2026 6:00',
            '1/5/2026 25',
        ]);
    });
});

describe('never the host', () => {
    test('nothing JavaScript would read as a number slips through', () => {
        refused(['0b11', '0o17', '1n', '1e3n', '+', ' \n5', '5\n', '1,5e', '١٢٣', 'null', 'undefined', '[1]']);
        taken([['1/1/2026 ', 46023]]);
    });
});
